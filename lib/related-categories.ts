export function relatedCategoryNames(categoryName: string, limit = 8): string[] {
  const related = new Set<string>();

  for (const group of CATEGORY_GROUPS) {
    if (!group.includes(categoryName)) continue;
    for (const name of group) {
      if (name !== categoryName) related.add(name);
    }
  }

  return [...related].slice(0, limit);
}
